import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packRoot = resolve(packageRoot, "../../standard-packs/mdbase-runtime/0.2.0");
const outputPath = resolve(packageRoot, "src/generated-schemas.ts");
const runtimeRecords = {
  runtime_workflow: "mdbase.runtime.workflow",
  runtime_policy: "mdbase.runtime.policy",
  runtime_provider_registration: "mdbase.runtime.provider-registration",
  runtime_capability_grant: "mdbase.runtime.capability-grant",
  runtime_run: "mdbase.runtime.run",
  runtime_action_attempt: "mdbase.runtime.action-attempt",
  runtime_checkpoint: "mdbase.runtime.checkpoint",
  runtime_timer: "mdbase.runtime.timer",
  runtime_diagnostic: "mdbase.runtime.diagnostic",
  runtime_dead_letter: "mdbase.runtime.dead-letter"
};

const schemas = {};
for (const [type, contract] of Object.entries(runtimeRecords)) {
  schemas[type] = JSON.parse(
    await readFile(resolve(packRoot, `schemas/${contract}/1.0.0.schema.json`), "utf8")
  );
}

const source = `// Generated by scripts/generate-schema-module.mjs. Do not edit directly.\n\nexport const GENERATED_RUNTIME_RECORD_SCHEMAS: Record<string, Record<string, unknown>> = ${JSON.stringify(schemas, null, 2)};\n`;
await writeFile(outputPath, source, "utf8");
