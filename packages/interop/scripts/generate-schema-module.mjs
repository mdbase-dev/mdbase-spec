import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const schemaRoot = resolve(packageRoot, "../../schemas");
const schemas = {
  contract: "v0.3/data-contract.schema.json",
  profile: "interop/v0.1/profile.schema.json",
  event: "interop/v0.1/event.schema.json",
  actionRequest: "interop/v0.1/action-request.schema.json",
  actionInvocation: "interop/v0.1/action-invocation.schema.json",
  actionOutcome: "interop/v0.1/action-outcome.schema.json",
  actionCancellation: "interop/v0.1/action-cancellation.schema.json",
  eventSourceDeclaration: "interop/v0.1/event-source-declaration.schema.json",
  actionProviderDeclaration: "interop/v0.1/action-provider-declaration.schema.json",
  conformanceClaim: "interop/v0.1/conformance-claim.schema.json"
};

const entries = await Promise.all(Object.entries(schemas).map(async ([name, relativePath]) => {
  const value = JSON.parse(await readFile(resolve(schemaRoot, relativePath), "utf8"));
  return [name, value];
}));

const output = [
  "// Generated by scripts/generate-schema-module.mjs. Do not edit directly.",
  "",
  `export const GENERATED_INTEROP_SCHEMAS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;`,
  ""
].join("\n");

await writeFile(resolve(packageRoot, "src/generated-schemas.ts"), output);
